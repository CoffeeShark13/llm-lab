"""Validate the article sources and render the LLM Lab static site."""

import json
import re
from html import escape as h
from pathlib import Path
from urllib.parse import urlsplit


ROOT = Path(__file__).resolve().parents[1]
CATEGORIES = {
    "本地部署": "DEPLOYMENT",
    "RAG": "RETRIEVAL",
    "AI Agent": "AGENTS",
    "模型原理": "INFERENCE",
}
SLUG = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")


def required_text(record, key):
    value = record.get(key)
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{key} 必須是非空文字")
    return value


def required_list(record, key, minimum=1, item_type=str):
    value = record.get(key)
    if not isinstance(value, list) or len(value) < minimum:
        raise ValueError(f"{key} 至少需要 {minimum} 項")
    for item in value:
        if not isinstance(item, item_type) or (item_type is str and not item.strip()):
            raise ValueError(f"{key} 的項目格式錯誤")
    return value


def validate(record, filename):
    if not isinstance(record, dict):
        raise ValueError("文章必須是 JSON 物件")
    slug = required_text(record, "slug")
    if not SLUG.fullmatch(slug) or filename != f"{slug}.json":
        raise ValueError("slug 格式錯誤或與檔名不符")
    required_text(record, "title")
    required_text(record, "summary")
    if required_text(record, "category") not in CATEGORIES:
        raise ValueError("文章類別不在允許清單中")
    for section in required_list(record, "sections", 2, dict):
        required_text(section, "heading")
        required_list(section, "paragraphs")
        if "code" in section:
            required_text(section, "code")
    required_list(record, "takeaways", 2)
    for reference in required_list(record, "references", item_type=dict):
        required_text(reference, "label")
        url = required_text(reference, "url")
        parts = urlsplit(url)
        if parts.scheme != "https" or not parts.hostname or any(c.isspace() for c in url):
            raise ValueError("參考資料必須使用有效的 HTTPS 網址")


def load_articles():
    articles = []
    for path in sorted((ROOT / "content").glob("*.json")):
        try:
            article = json.loads(path.read_text(encoding="utf-8"))
            validate(article, path.name)
        except ValueError as error:
            raise ValueError(f"{path.name}：{error}") from error
        articles.append(article)
    if not articles:
        raise ValueError("content/ 裡沒有文章")
    return sorted(articles, key=lambda article: tuple(CATEGORIES).index(article["category"]))


